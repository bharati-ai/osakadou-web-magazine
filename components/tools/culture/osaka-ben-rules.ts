// 標準語 → 大阪弁, rule-based (no morphological analysis). Order matters: phrases, then grammar, then particles,
// then plain vocabulary. Self-check: `node components/tools/culture/osaka-ben.check.ts`.
// ponytail: regex rules only; a few homographs (e.g. kana 「すんだ」=済んだ) can misfire. Add a tokenizer if that matters.

type Rule = [RegExp, string | ((m: string, ...g: string[]) => string)];

// Words a later rule would break. Swapped for private-use placeholders and restored at the end.
const LOCK: string[] = [
  "すんません", "きたない", "おさない", "はかない", "あっけない", "そっけない", "なさけない", "情けない", "あどけない",
  "さりげない", "なにげない", "何気ない", "大人げない", "もったいない", "だらしない", "ぎこちない", "おぼつかない",
  "惜しみない", "向こう", "かわいい", "可愛い", "じゃんけん",
];
const L = (s: string) => String.fromCharCode(0xe000 + LOCK.indexOf(s));

const END = "(?=[。．.！!？?、，,…〜～ー」』）)\\s]|$)";
const CS = "(^|[。！!？?、\\n「『（(\\s])"; // clause start
// hiragana that may sit right before copula だ (not た・だ・ま・く・ん・い・や・っ: ただ, まだ, ください, 飲んだ, 泳いだ, やだ)
const HIRA_OK = [..."ぁあぃぅうぇえぉおかがきぎぐけげこごさざしじすずせぜそぞちぢつづてでとどなにぬねのはばぱひびぴふぶぷへべぺほぼぽみむめもゃゅゆょよらりるれろゎわをゔ"].join("");
const AK = (x: string) => (x === "いけません" || x === "なりません" ? "あきません" : "あかん");
const NG = "(いけない|いけません|だめ|ダメ|駄目)";
// explanatory tails after んだ / のだ
const TAIL = "(ろう|ろ|よね|よな|よ|けれど|けど|から|って|もん|ね|な)";
const tailNen = (t = "") => ({ よね: "な", よな: "な", けれど: "けど", けど: "けど", って: "て", もん: "もん" } as Record<string, string>)[t] ?? "";
// んだろう → んやろ, んだね → んやな, んだから → んやから; everything else → ねん / てん
const yaTail = (t?: string) => (t === "ろう" || t === "ろ" ? "やろ" : t === "ね" || t === "な" ? "やな" : t === "から" ? "やから" : null);
// negative stems: 行か|食べ|起き|し|来|見… + ない
const STEM = "(し|来|見|寝|出|[かさたなまばわらえけせてねべめれげきじりびぎみ]|(?<=[んい])で)";
const neg = (st: string, kind: "nai" | "naide" | "naito" | "req") => {
  if (kind === "req" || kind === "naide" || kind === "naito") {
    const base = st === "し" ? "せ" : st;
    return base + (kind === "req" ? "んといて" : "んと");
  }
  if (st === "し") return "せえへん";
  if (st === "来") return "けえへん";
  if (st === "見") return "見いひん";
  if (st === "寝" || st === "出") return st + "えへん";
  if (st === "ら") return "らん";
  return st + "へん";
};

const RULES: Rule[] = [
  // 1. set phrases and vocabulary that later rules would otherwise mangle
  [/ありがとうございま(す|した)|ありがとう/g, "おおきに"],
  [/すみません|すいません/g, L("すんません")],
  [/ごめんなさい/g, "ごめんな"],
  [/しょうがない|仕方(が)?ない|しかた(が)?ない/g, "しゃあない"],
  [/かまわない|構わない/g, "かまへん"],
  [/すまない/g, "すまん"],
  [/いいえ/g, "いや"],
  [/さようなら|さよなら/g, "さいなら"],
  [/とても|すごく|非常に/g, "めっちゃ"],
  [/どうして(?=[、？?！!\p{Script=Han}]|$)|なぜ(?!なら)/gu, "なんで"],
  [/あなた/g, "あんた"],
  [/馬鹿|バカ|ばか(?![りば])/g, "あほ"],
  [/うるさい/g, "やかましい"],
  [/ずるい/g, "こすい"],
  [/飴(?!ちゃん)/g, "飴ちゃん"],
  [/(面白|おもしろ)(?=[いかくそ])/g, "おもろ"],
  [/捨て(る|た|て|ない|ます|よう)/g, (_, t) => "ほか" + ({ る: "す", た: "した", て: "して", ない: "さない", ます: "します", よう: "そう" } as Record<string, string>)[t]],
  [/片付け(る|た|て|ます)/g, (_, t) => "なお" + ({ る: "す", た: "した", て: "して", ます: "します" } as Record<string, string>)[t]],
  [/(早|はや)く(?!な)/g, (_, a) => (a === "早" ? "早よ" : "はよ")],
  [/けれども|けれど/g, "けど"],

  // 2. ウ音便 (言うた, 買うた, もろた, 思た)
  [/(言|買)っ(て|た)/g, "$1う$2"],
  [/(もら|貰)っ(て|た)/g, "もろ$2"],
  [/思っ(て|た)/g, "思$1"],

  // 3. 〜てしまう → 〜てまう / 〜てもうた
  [/([てで])しまった/g, "$1もうた"],
  [/([てで])しまっ(?=て)/g, "$1もう"],
  [/([てで])しまう/g, "$1まう"],
  [/んじゃった/g, "んでもうた"],
  [/ちゃった/g, "てもうた"],
  [/んじゃう/g, "んでまう"],
  [/(?<=[\p{Script=Han}ぁ-ん])ちゃう/gu, "てまう"],
  [new RegExp(CS + "しまった", "g"), "$1しもた"],

  // 4. prohibition and obligation → あかん
  [new RegExp("ん(では|じゃ)" + NG, "g"), (_, __, x) => "んだら" + AK(x)],
  [new RegExp("(では|じゃ)" + NG, "g"), (_, __, x) => "やったら" + AK(x)],
  [new RegExp("(ては|ちゃ)" + NG, "g"), (_, __, x) => "たら" + AK(x)],
  [/しなければ(ならない|いけない|なりません|いけません)|しなきゃ(いけない|ならない)|しなくちゃ(いけない|ならない)|しないと(いけない|いけません|だめ|ダメ)/g, (m) => "せな" + AK(m.endsWith("ません") ? "いけません" : "")],
  [/しなきゃ|しなくちゃ/g, "せな"],
  [/なければ(ならない|いけない|なりません|いけません)|なきゃ(いけない|ならない)|なくちゃ(いけない|ならない)|ないと(いけない|いけません|だめ|ダメ)/g, (m) => "な" + AK(m.endsWith("ません") ? "いけません" : "")],
  [/なきゃ|なくちゃ/g, "な"],
  [/(だめ|ダメ|駄目)だった/g, "あかんかった"],
  [/(だめ|ダメ|駄目)です/g, "あきません"],
  [/(だめ|ダメ|駄目)だ?/g, "あかん"],
  [/いけない/g, "あかん"],
  [/いけません/g, "あきません"],
  [/できな(い|かった)/g, (_, t) => (t === "い" ? "でけへん" : "でけへんかった")],

  // 5. いる → おる (after a particle), 〜ている → 〜てる
  [/([にがも])い(る|た(?![いくかけ])|ない|なかった|よう)/g, (_, p, t) => p + "お" + ({ る: "る", た: "った", ない: "らん", なかった: "らんかった", よう: "ろ" } as Record<string, string>)[t]],
  [/(て|(?<=[んい])で)い(?=る|た(?![いくかけ])|な|ま)/g, "$1"],

  // 6. clause openers: せやから, せやけど, せやかて, ほんなら, ほな, せや
  [new RegExp(CS + "だから", "g"), "$1せやから"],
  [new RegExp(CS + "だけど", "g"), "$1せやけど"],
  [new RegExp(CS + "だって", "g"), "$1せやかて"],
  [new RegExp(CS + "(だったら|それなら|それだったら)", "g"), "$1ほんなら"],
  [new RegExp(CS + "(それじゃあ|それじゃ|それでは|じゃあ|じゃ|では)(?=[、,！!\\s]|ね|また|$)", "g"), "$1ほな"],
  [new RegExp(CS + "そう(?=だ|でしょ|だろ)", "g"), "$1せ"],
  [/なんだかんだ/g, "なんやかんや"],
  [/なんだか/g, "なんか"],
  [new RegExp(CS + "なんだ", "g"), "$1なんや"],

  // 7. explanatory のだ → ねん / てん
  [/そうなんだ(よね|よな|よ)/g, (_, t) => "そうやねん" + tailNen(t)],
  [new RegExp("そうなんだ" + END, "g"), "そうなんや"],
  [new RegExp("な[んの]だ(?:" + TAIL + "|" + END + ")", "g"), (_, t?: string) =>
    yaTail(t) ? "なん" + yaTail(t) : t === "って" ? "なんやって" : "やねん" + tailNen(t)],
  [new RegExp("([ただ])んだ(?:" + TAIL + "|" + END + ")", "g"), (_, c, t?: string) =>
    yaTail(t) ? c + "ん" + yaTail(t) : (c === "た" ? "てん" : "でん") + tailNen(t)],
  [new RegExp("([うくすつぬむるぐいて])[んの]だ(?:" + TAIL + "|" + END + ")", "g"), (_, c, t?: string) =>
    yaTail(t) ? c + "ん" + yaTail(t) : c + (c === "て" ? "んねん" : "ねん") + tailNen(t)],
  [/んじゃない/g, "んちゃう"],

  // 8. じゃない / ではない → ちゃう, やない, やん
  [/じゃないですか/g, "やないですか"],
  [/じゃないか/g, "やんか"],
  [/じゃないです|じゃありません|ではありません|ではないです/g, "ちゃいます"],
  [/じゃなかった|ではなかった/g, "ちゃうかった"],
  [/(じゃ|では)なく/g, "やなく"],
  [/((?<!きれ|嫌|きら)い|[たるうくすつむぬぐ])じゃない(?=[。！!？?]|$)/g, "$1やん"],
  [/じゃない/g, "ちゃう"],
  [/ではない/g, "やない"],
  [/じゃん/g, "やん"],

  // 9. copula だ → や
  [/(いや|嫌)だ(よ|ね|な)?/g, (_, a, t?: string) => (a === "嫌" ? "嫌や" : "いやや") + (t === "よ" ? "わ" : t ? "な" : "")],
  [/(でしょ|だろ)う?/g, "やろ"],
  [new RegExp(
    `(?<=[\\p{Script=Han}\\p{Script=Katakana}ーA-Za-z0-9０-９${HIRA_OK}]|きれい|嫌い|きらい|みたい|さん)だ(?:(よね|よな|よ|けれど|けど|から|った|って|もん|ね|な|と|し(?=[、,]))|${END})`, "gu"),
  (_, t?: string) => "や" + (({ よね: "んな", よな: "んな", よ: "で", けれど: "けど", ね: "な" } as Record<string, string>)[t ?? ""] ?? t ?? "")],

  // 10. 違う → ちゃう
  [/違い?ます/g, "ちゃいます"],
  [/違って/g, "ちごて"],
  [/違った/g, "ちゃうかった"],
  [/違う|ちがう/g, "ちゃう"],

  // 11. negatives: 行かへん, 知らん, せえへん, 見んといて
  [/ことはない|ことない/g, "ことあらへん"],
  [new RegExp("しかな(い|かった)(?=[よねなのしけか]|" + END + ")", "g"), (_, t) => "しかあらへん" + (t === "い" ? "" : "かった")],
  [new RegExp("(?<!で)もない(?=[よねなのしけか]|" + END + ")", "g"), "もあらへん"],
  [new RegExp(STEM + "ないで(?=ください|くれ|ほしい|もらえ|ね|よ|な|[。！!？?…」』\\s]|$)", "gu"), (_, s) => neg(s, "req")],
  [new RegExp(STEM + "ないで", "gu"), (_, s) => neg(s, "naide")],
  [new RegExp(STEM + "ないと", "gu"), (_, s) => neg(s, "naito")],
  [new RegExp(STEM + "なかっ(?=[たて])", "gu"), (_, s) => neg(s, "nai") + "かっ"],
  [new RegExp(STEM + "ない", "gu"), (_, s) => neg(s, "nai")],

  // 12. sentence-final particles: 行くん？ 行くねん。 行くで。 ええな。
  [/([うくすつぬむるぐいたな])の(?=[？?])/g, "$1ん"],
  [/([うくすつぬむるぐい]|た)の(よ)?(?=[。！!…]|$)/g, (_, c) => (c === "た" ? "てん" : c + "ねん")],
  [new RegExp("([こそともろごぼの])うよ" + END, "g"), "$1うや"],
  [new RegExp("([てで])よ" + END, "g"), "$1や"],
  [new RegExp("((?<![でま])す|[うくつぬむるぐいた]|(?<!な)ん)よ" + END, "g"), "$1で"],
  [new RegExp("(?<!です|ます|ました|でした|ません|まへん|ましょ|さい|[なの])ね" + END, "g"), "な"],

  // 13. volitional 行こう → 行こ, しよう → しよ
  [/([\p{Script=Han}ばやなまらい][こともろごぼの])う(?=[。！!？?、…」』\s]|$|か)/gu, "$1"],
  [/([\p{Script=Han}しべめけれてせねえみき])よう(?=[。！!？?、…」』\s]|$|か)/gu, "$1よ"],
  [/ましょう(?=[。！!？?、…」』\s]|$|か)/g, "ましょ"],

  // 14. plain vocabulary (after the copula rules so 本当だ → ほんまや)
  [/(?<![いわ])いい(?![まただ])/g, "ええ"],
  [/良い/g, "ええ"],
  [/本当|ほんとう|ほんと/g, "ほんま"],
  [/たくさん|沢山/g, "ぎょうさん"],
  [/まあまあ/g, "ぼちぼち"],
  [/いくら/g, "なんぼ"],
  [/(良|よ)くな(い|かった)/g, "ような$2"],
  [/(?<!す)くな(い|かった)/g, "な$1"],
  [/ません/g, "まへん"],
];

export function toOsakaBen(src: string): string {
  let s = src.replace(/[-]/g, "");
  LOCK.forEach((w, i) => { s = s.replaceAll(w, String.fromCharCode(0xe000 + i)); });
  for (const [re, to] of RULES) s = typeof to === "string" ? s.replace(re, to) : s.replace(re, to);
  return s.replace(/[-]/g, (c) => LOCK[c.charCodeAt(0) - 0xe000]);
}
